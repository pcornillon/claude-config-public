#!/usr/bin/env bash
#
# Maintain the "Session logs held elsewhere" block in a repo's LOG.md (D56).
#
#   ./foreign-keys.sh [--check] [repo ...]     no argument means the current directory
#
# A LOG.md row whose session key does not resolve locally is not an error: D34 puts a
# session log in the repository whose files changed, so a session driven from one repo
# that did its work in another leaves the row here and the log there. D55 leaves such a
# key unlinked, which says "not here" but not "then where?". This writes the answer.
#
# The block sits between two HTML-comment markers and is REGENERATED in full each run,
# so it is idempotent and it self-corrects when a log is later added, moved or renamed.
# Nothing outside the markers is touched, and no row is edited.
#
# Cross-repo relative links are deliberately NOT emitted: they break the moment either
# repo moves, and ~/Git_Repos is not guaranteed on another machine. The block names the
# repo and the file; finding it is one `ls`.
#
# Scans every sibling repo of the target that has a CLAUDE.md, so it needs them cloned
# to see them. A key it cannot place anywhere is listed as such rather than dropped —
# that is a real gap, and hiding it would be worse than naming it.

set -uo pipefail
check=0
[ "${1:-}" = "--check" ] && { check=1; shift; }
[ $# -eq 0 ] && set -- .

for repo in "$@"; do
  [ -f "$repo/LOG.md" ] || { echo "skip $repo — no LOG.md"; continue; }
  check=$check python3 - "$repo" <<'PY'
import io, os, re, sys, glob, collections

repo  = os.path.abspath(sys.argv[1])
check = os.environ.get("check") == "1"
root  = os.path.dirname(repo)
name  = os.path.basename(repo)
BEG, END = "<!-- FOREIGN-KEYS:BEGIN -->", "<!-- FOREIGN-KEYS:END -->"

def key_of(path):
    p = os.path.basename(path)[:-3].split("_")
    if len(p) >= 4: return "%s_%s" % (p[1], "_".join(p[3:]))
    if len(p) == 3: return p[1]
    return None

# every session log in every sibling Claude project
idx = collections.defaultdict(list)
for d in sorted(os.listdir(root)):
    if not os.path.isfile(os.path.join(root, d, "CLAUDE.md")): continue
    for p in sorted(glob.glob(os.path.join(root, d, "SESSIONS", "*.md"))):
        k = key_of(p)
        if k: idx[k].append((d, os.path.basename(p)))

local = {k for k, v in idx.items() if any(r == name for r, _ in v)}

# keys used in the KEY POSITION of an entry row that do not resolve locally
KEY = r"[0-9]{4}(?:_[A-Za-z0-9.-]+)?"
pat = re.compile(r"\[`(%s)`\]\([^)]*\)|`(%s)`" % (KEY, KEY))
logp = os.path.join(repo, "LOG.md")
src  = io.open(logp, encoding="utf-8").read()
rows = collections.Counter()
for ln in src.split("\n"):
    if not re.match(r"^- (?:★ )?\*\*P", ln): continue
    m = pat.search(ln)
    if not m: continue
    k = m.group(1) or m.group(2)
    if k not in local: rows[k] += 1

if rows:
    out = [BEG, "",
           "**Session logs held elsewhere.** These keys name sessions whose log lives in",
           "another repository, because the session changed that repository's files (D34).",
           "They are left unlinked on purpose — a cross-repo path would break as soon as",
           "either repo moved. Regenerated by `claude-config-public/foreign-keys.sh` (D56).", ""]
    out += ["| key | rows | session log |", "|---|---|---|"]
    for k in sorted(rows):
        where = [(r, f) for r, f in idx.get(k, []) if r != name]
        if where:
            w = "<br>".join("`%s/SESSIONS/%s`" % (r, f) for r, f in where)
        else:
            w = "**not found in any cloned repo**"
        out.append("| `%s` | %d | %s |" % (k, rows[k], w))
    out += ["", END]
    block = "\n".join(out)
else:
    block = ""

if BEG in src and END in src:
    new = re.sub(re.escape(BEG) + r".*?" + re.escape(END), lambda _: block, src, flags=re.S)
    if not block: new = re.sub(r"\n*" + re.escape(BEG) + r".*?" + re.escape(END) + r"\n*", "\n\n", src, flags=re.S)
    where = "regenerated"
else:
    if not block:
        print("%-42s no foreign keys" % name); raise SystemExit(0)
    # after the header, immediately before the first "---" or the first "## "
    m = re.search(r"^(---|## )", src, re.M)
    at = m.start() if m else len(src)
    new = src[:at] + block + "\n\n" + src[at:]
    where = "inserted"

print("%-42s %s: %d foreign key(s), %d row(s)%s"
      % (name, ("would be " + where) if check else where, len(rows), sum(rows.values()),
         "" if not check else ""))
if not check and new != src:
    io.open(logp, "w", encoding="utf-8").write(new)
PY
done
